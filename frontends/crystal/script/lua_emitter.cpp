// Control flow with proper goto labels
void LuaEmitter::emit_op(std::ostream& out, const Op_Jump& op) {
    auto it = state_.address_to_label.find(op.target.rom_address);
    if (it != state_.address_to_label.end()) {
        emit_line(out, "goto " + it->second);
    } else {
        emit_comment(out, "jump to " + op.target.name + " (target not in script)");
    }
}

void LuaEmitter::emit_op(std::ostream& out, const Op_JumpIf& op) {
    auto it = state_.address_to_label.find(op.target.rom_address);
    if (it != state_.address_to_label.end()) {
        // Determine condition based on Op_JumpIf.condition
        // condition is "true", "false", "== N", "!= N", "> N", "< N"
        std::string cond;
        if (op.condition == "true") {
            cond = "result";
        } else if (op.condition == "false") {
            cond = "not result";
        } else {
            // Comparison conditions like "== 5", "!= 3"
            cond = "result " + op.condition;
        }
        emit_line(out, "if " + cond + " then goto " + it->second + " end");
    } else {
        emit_comment(out, "conditional jump to " + op.target.name + " (target not in script)");
    }
}

