void LuaEmitter::emit_all(const ScriptIRSet& scripts, const std::filesystem::path& dir) {
    std::filesystem::create_directories(dir);
    
    for (const auto& script : scripts.scripts) {
        std::filesystem::path path = dir / (script.name + ".lua");
        std::ofstream out(path);
        if (out) {
            emit(script, out);
        }
    }
}

