LuaEmitter::LuaEmitter(EmitterConfig config) : config_(config) {}

void LuaEmitter::emit_indent(std::ostream& out) {
    for (int i = 0; i < current_indent_ * config_.indent_width; ++i) {
        out << ' ';
    }
}

void LuaEmitter::emit_line(std::ostream& out, const std::string& line) {
    emit_indent(out);
    out << line << "\n";
}

void LuaEmitter::emit_comment(std::ostream& out, const std::string& comment) {
    emit_indent(out);
    out << "-- " << comment << "\n";
}

std::string LuaEmitter::escape_string(const std::string& s) {
    std::string result;
    result.reserve(s.size() + 10);
    for (char c : s) {
        switch (c) {
            case '\n': result += "\\n"; break;
            case '\r': result += "\\r"; break;
            case '\t': result += "\\t"; break;
            case '"': result += "\\\""; break;
            case '\\': result += "\\\\"; break;
            default: result += c; break;
        }
    }
    return result;
}

std::string LuaEmitter::make_label_function_name(const LabelRef& ref) {
    std::string name = ref.name;
    for (char& c : name) {
        if (!isalnum(c) && c != '_') {
            c = '_';
        }
    }
    if (!name.empty() && isdigit(name[0])) {
        name = "_" + name;
    }
    return name;
}

void LuaEmitter::emit_header(std::ostream& out, const ScriptIR& script) {
    out << "-- Script: " << script.name << "\n";
    if (config_.emit_address_comments) {
        out << "-- ROM: 0x" << std::hex << script.rom_start << std::dec << "\n";
    }
    out << "-- Generated by Enginemon Crystal Frontend\n";
    out << "\n";
    out << "local script = {}\n\n";
}

void LuaEmitter::emit_footer(std::ostream& out, const ScriptIR& script) {
    out << "\nreturn script\n";
}

std::string LuaEmitter::emit(const ScriptIR& script) {
    std::ostringstream out;
    emit(script, out);
    return out.str();
}

// Collect all jump targets to know which addresses need labels
static std::set<uint32_t> collect_jump_targets(const ScriptIR& script) {
    std::set<uint32_t> targets;
    for (const auto& inst : script.instructions) {
        std::visit([&targets](const auto& op) {
            using T = std::decay_t<decltype(op)>;
            if constexpr (std::is_same_v<T, Op_Jump>) {
                targets.insert(op.target.rom_address);
            } else if constexpr (std::is_same_v<T, Op_JumpIf>) {
                targets.insert(op.target.rom_address);
            }
        }, inst.op);
    }
    return targets;
}

void LuaEmitter::emit(const ScriptIR& script, std::ostream& out) {
    state_.script = &script;
    state_.address_to_label.clear();
    current_indent_ = 0;
    
    // Collect all jump targets
    auto jump_targets = collect_jump_targets(script);
    
    // Build address -> label mapping
    for (const auto& inst : script.instructions) {
        if (jump_targets.count(inst.rom_address)) {
            std::ostringstream label;
            label << "label_" << std::hex << inst.rom_address;
            state_.address_to_label[inst.rom_address] = label.str();
        }
    }
    
    // Check if we have any jump targets (which means labels after returns)
    bool needs_end_label = !state_.address_to_label.empty();
    
    emit_header(out, script);
    
    // Main function
    out << "function script.main(ctx)\n";
    current_indent_ = 1;
    
    // Initialize result variable that check operations use
    emit_line(out, "local result = false");
    emit_line(out, "");
    
    for (const auto& inst : script.instructions) {
        // Emit label if this address is a jump target
        auto label_it = state_.address_to_label.find(inst.rom_address);
        if (label_it != state_.address_to_label.end()) {
            emit_line(out, "::" + label_it->second + "::");
        }
        
        // For End operations when we have labels, emit goto to end instead of return
        // (because return can't be followed by anything including labels)
        bool is_end = std::holds_alternative<Op_End>(inst.op);
        if (is_end && needs_end_label) {
            emit_line(out, "goto script_end");
        } else {
            emit_instruction(out, inst);
        }
    }
    
    // Add end label if needed
    if (needs_end_label) {
        emit_line(out, "::script_end::");
    }
    
    current_indent_ = 0;
    out << "end\n";
    
    emit_footer(out, script);
}

void LuaEmitter::emit_instruction(std::ostream& out, const Instruction& inst) {
    if (config_.emit_address_comments) {
        std::ostringstream comment;
        comment << "0x" << std::hex << inst.rom_address;
        emit_comment(out, comment.str());
    }
    
    std::visit([this, &out](const auto& op) { emit_op(out, op); }, inst.op);
}

